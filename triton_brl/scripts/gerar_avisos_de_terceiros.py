def edicao() -> str:
    """A edição desta pasta (BRL, INT ou PRT): pelo nome da pasta e, se não bastar, por TRITON_EDITION."""
    nome = RAIZ.name.lower()
    for codigo in ("brl", "int", "prt"):
        if nome.endswith("_" + codigo):
            return codigo.upper()
    codigo = os.environ.get("TRITON_EDITION", "").strip().upper()
    codigo = {"POR": "PRT"}.get(codigo, codigo)
    return codigo if codigo in ("BRL", "INT", "PRT") else "BRL"


