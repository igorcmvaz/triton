def _translate_composite(text, phrases):
    translated = text
    for source, target in sorted(phrases.items(), key=lambda item: len(item[0]), reverse=True):
        translated = translated.replace(source, target)
    return translated


def tr(text, lang=None):
    """Traduz um rótulo do catálogo, preservando pt-BR como idioma-fonte."""
    lang = lang or get_current_lang()
    if lang == "pt":
        if _variante_portugal():
            from triton.ui.portugues_de_portugal import para_portugal
            return para_portugal(text)
        return text
    if lang == "en":
        return _DICTIONARY.get(text, text)
    catalog = _SPANISH_DICTIONARY if lang == "es" else _CHINESE_DICTIONARY
    direct = catalog.get(text)
    if direct is not None:
        return direct
    phrases = _SPANISH_PHRASES if lang == "es" else _CHINESE_PHRASES
    composite = _translate_composite(text, phrases)
    return composite if composite != text else _DICTIONARY.get(text, text)


