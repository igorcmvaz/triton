import os
import sys
from PySide6.QtCore import QSettings, Qt
from PySide6.QtGui import QIcon, QPixmap
from PySide6.QtWidgets import QApplication, QDialog, QVBoxLayout, QHBoxLayout, QLabel, QPushButton

_runtime_language = None
_runtime_theme = None


def _preferencias() -> QSettings:
    """Preferências separadas por edição: instaladas lado a lado, não dividem idioma."""
    from triton.core.edition import abrir_preferencias

    return abrir_preferencias()


def _idioma_padrao() -> str:
    from triton.core.edition import is_int_edition

    return "en" if is_int_edition() else "pt"


def get_current_lang():
    if _runtime_language is not None:
        return _runtime_language
    settings = _preferencias()
    lang = str(settings.value("language", _idioma_padrao()))
    return lang if lang in get_available_languages() else _idioma_padrao()


def set_current_lang(lang):
    global _runtime_language
    _runtime_language = lang if lang in get_available_languages() else "pt"
    settings = _preferencias()
    settings.setValue("language", _runtime_language)
    settings.sync()


def is_language_set():
    if _runtime_language is not None:
        return True
    settings = _preferencias()
    return settings.contains("language")


def get_current_theme():
    """A edição atual do Triton utiliza apenas o tema claro."""
    return "light"


def get_resource_path(relative_path):
    """Retorna o caminho absoluto para recursos, resolvendo o diretório temporário do PyInstaller."""
    if hasattr(sys, '_MEIPASS'):
        return os.path.join(sys._MEIPASS, relative_path)
    return os.path.join(os.path.abspath(os.path.dirname(os.path.dirname(os.path.dirname(__file__)))), relative_path)


def _variante_portugal() -> bool:
    """Na Edição Ibérica, o português da interface é o de Portugal (ver portugues_de_portugal)."""
    from triton.core.edition import is_ibe_edition

    return is_ibe_edition()


def em_portugues_da_edicao(texto: str) -> str:
    """Um texto escrito direto em português (fora do catálogo de tr), no português da edição.

    Telas que escolhem o texto por `if not ingles` não passam por tr(); na Portugal, o
    glossário (portugues_de_portugal) vale para elas também. Fora da Portugal, ou em
    outra língua, o texto volta como veio.
    """
    if not texto or not _variante_portugal() or get_current_lang() != "pt":
        return texto
    from triton.ui.portugues_de_portugal import para_portugal
    return para_portugal(texto)


def get_available_languages():
    """Idiomas presentes no núcleo ou selecionados como componentes do instalador."""
    available = {"pt": "Português (Portugal)" if _variante_portugal() else LANGUAGES["pt"],
                 "en": LANGUAGES["en"]}
    for code in ("es", "zh"):
        manifest = get_resource_path(os.path.join("data", "languages", f"{code}.json"))
        if os.path.isfile(manifest):
            available[code] = LANGUAGES[code]
    return available


def restart_app():
    """Reinicia o aplicativo de forma limpa, compatível com PyInstaller e Inno Setup."""
    QApplication.quit()
    import subprocess
    if getattr(sys, 'frozen', False):
        subprocess.Popen([sys.executable])
    else:
        subprocess.Popen([sys.executable] + sys.argv)


class FirstRunLangDialog(QDialog):
    """
    Diálogo exibido na primeira execução para que o usuário escolha o idioma de instalação.
    """
    def __init__(self):
        super().__init__()
        self.setWindowTitle("Triton — Language / Idioma")
        self.resize(430, 260)
        for icone_rel in (
            os.path.join("icons", "triton.ico"),
            os.path.join("icons", "icon.ico"),
            os.path.join("icons", "triton_brl.png"),
            os.path.join("icons", "triton_int.png"),
            os.path.join("icons", "triton_ibe.png"),
            os.path.join("icons", "triton.png"),
            os.path.join("icons", "icon.png"),
            os.path.join("icons", "Triton2.png"),
        ):
            icone_path = get_resource_path(icone_rel)
            if os.path.isfile(icone_path):
                self.setWindowIcon(QIcon(icone_path))
                break
        self.init_ui()

    def init_ui(self):
        layout = QVBoxLayout()
        layout.setSpacing(10)
        layout.setContentsMargins(15, 15, 15, 15)

        logo_label = QLabel()
        logo_label.setAlignment(Qt.AlignCenter)
        for icone_rel in (
            os.path.join("icons", "triton_brl.png"),
            os.path.join("icons", "triton_int.png"),
            os.path.join("icons", "triton_ibe.png"),
            os.path.join("icons", "triton.png"),
            os.path.join("icons", "icon.png"),
            os.path.join("icons", "triton.ico"),
            os.path.join("icons", "icon.ico"),
        ):
            icone_path = get_resource_path(icone_rel)
            if os.path.isfile(icone_path):
                pixmap = QPixmap(icone_path)
                if not pixmap.isNull():
                    logo_label.setPixmap(pixmap.scaled(48, 48, Qt.KeepAspectRatio, Qt.SmoothTransformation))
                    layout.addWidget(logo_label)
                    break

        lbl = QLabel(
            "Selecione o idioma de exibição do Triton.\n"
            "Select the display language for Triton."
        )
        lbl.setAlignment(Qt.AlignCenter)
        lbl.setWordWrap(True)
        layout.addWidget(lbl)

        btn_layout = QHBoxLayout()
        btn_pt = QPushButton("Português (Brasil)")
        btn_pt.setStyleSheet("font-weight: bold; padding: 8px; background-color: #0284c7; color: white; border-radius: 4px;")
        btn_pt.clicked.connect(self.select_pt)

        btn_en = QPushButton("English (US)")
        btn_en.setStyleSheet("font-weight: bold; padding: 8px; background-color: #10b981; color: white; border-radius: 4px;")
        btn_en.clicked.connect(self.select_en)

        btn_layout.addWidget(btn_pt)
        btn_layout.addWidget(btn_en)
        if "es" in get_available_languages():
            btn_es = QPushButton("Español")
            btn_es.clicked.connect(lambda: self.select_language("es"))
            btn_layout.addWidget(btn_es)
        if "zh" in get_available_languages():
            btn_zh = QPushButton("中文")
            btn_zh.clicked.connect(lambda: self.select_language("zh"))
            btn_layout.addWidget(btn_zh)
        layout.addLayout(btn_layout)

        self.setLayout(layout)

    def select_pt(self):
        set_current_lang("pt")
        self.accept()

    def select_en(self):
        set_current_lang("en")
        self.accept()

    def select_language(self, lang):
        set_current_lang(lang)
        self.accept()


def check_first_run_language():
    """
    Se o idioma ainda não estiver configurado nos registros, exibe o modal de seleção.
    Na edição com a base E-OBS (IBE), pergunta também, uma vez por instalação, o uso dos dados.
    """
    _escolher_idioma_na_primeira_vez()
    from triton.core.edition import usa_dados_de_portugal
    if usa_dados_de_portugal():
        from triton.ui.dialogs.dialog_licenca_eobs import perguntar_uso_se_necessario
        perguntar_uso_se_necessario()


def _escolher_idioma_na_primeira_vez():
    if not is_language_set():
        from triton.core.edition import is_int_edition
        if is_int_edition():
            # A Internacional abre em inglês; o idioma muda depois pela interface.
            set_current_lang("en")
            return
        if _variante_portugal():
            # A Portugal abre em português de Portugal; o idioma muda depois pela interface.
            set_current_lang("pt")
            return
        from PySide6.QtCore import Qt
        dialog = FirstRunLangDialog()
        dialog.exec()


